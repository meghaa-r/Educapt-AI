import React, { useState, useEffect } from 'react';
import ReactFlow, { Background, Controls, MiniMap } from 'reactflow';
import 'reactflow/dist/style.css';
import { generateAIMindMap } from '../../services/documentService';

export default function MindMapPanel({ document, onNodeClick }) {
  const [nodes, setNodes] = useState([]);
  const [edges, setEdges] = useState([]);
  const [isGenerating, setIsGenerating] = useState(false);
  const [error, setError] = useState(null);

  useEffect(() => {
    // If there is no text to analyze, don't try to fetch
    if (!document || !document.content) return;

    async function fetchMindMap() {
      setIsGenerating(true);
      setError(null);
      
      try {
        // Send the first 3000 characters to Ollama to keep generation times fast
        const textToAnalyze = document.content.substring(0, 3000);
        const aiData = await generateAIMindMap(textToAnalyze);
        
        // Format Backend JSON into strict React Flow format
        const formattedNodes = (aiData.nodes || []).map((n, index) => ({
          id: String(n.id || `node-${index}`),
          data: { label: n.label || n.id },
          // Provide default positions if backend forgets them
          position: { 
            x: typeof n.x === 'number' ? n.x : Math.random() * 400, 
            y: typeof n.y === 'number' ? n.y : Math.random() * 400 
          },
          style: { 
            background: 'var(--bg-surface, #fff)', 
            border: '2px solid var(--accent-primary, #007bff)',
            borderRadius: '8px',
            padding: '10px',
            fontWeight: 'bold',
            color: 'var(--text-primary, #111)'
          }
        }));

        const formattedEdges = (aiData.edges || []).map((e, index) => ({
          id: String(e.id || `edge-${index}`),
          source: String(e.source),
          target: String(e.target),
          label: e.label || '',
          animated: true, // Adds a cool flowing animation to the connections!
          style: { stroke: 'var(--accent-primary, #007bff)', strokeWidth: 2 }
        }));

        setNodes(formattedNodes);
        setEdges(formattedEdges);

      } catch (err) {
        console.error("AI Error:", err);
        setError("The AI pipeline could not generate this map. Ensure Ollama is running on the backend.");
      } finally {
        setIsGenerating(false);
      }
    }

    fetchMindMap();
  }, [document]); // Re-run whenever the document changes

  return (
    <div style={{ flex: 1, height: '100vh', display: 'flex', flexDirection: 'column', backgroundColor: 'var(--bg-reader, #f9fafb)' }}>
      <header style={{ padding: '2rem', borderBottom: '1px solid var(--border-color, #ccc)', background: 'var(--bg-surface, #fff)' }}>
        <h1 style={{ fontSize: '1.5rem', fontWeight: 'bold' }}>Concept Map: {document?.title || "Loading..."}</h1>
        <p style={{ color: 'var(--text-secondary, #666)' }}>Visual associative graph generated by AI.</p>
      </header>

      <div style={{ flex: 1, position: 'relative' }}>
        {isGenerating && (
          <div style={{ position: 'absolute', inset: 0, display: 'flex', flexDirection: 'column', alignItems: 'center', justifyContent: 'center', zIndex: 10, background: 'rgba(255,255,255,0.8)' }}>
            <div style={{ width: '40px', height: '40px', border: '4px solid var(--accent-subtle, #e0e0e0)', borderTop: '4px solid var(--accent-primary, #007bff)', borderRadius: '50%', animation: 'spin 1s linear infinite' }} />
            <p style={{ marginTop: '1rem', fontWeight: 'bold' }}>Ollama AI is mapping concepts...</p>
            <style>{`@keyframes spin { 0% { transform: rotate(0deg); } 100% { transform: rotate(360deg); } }`}</style>
          </div>
        )}

        {error && (
          <div style={{ padding: '2rem', color: 'red', textAlign: 'center' }}>
            <p>⚠️ {error}</p>
          </div>
        )}

        {!isGenerating && !error && nodes.length === 0 && (
          <div style={{ padding: '4rem', textAlign: 'center', color: 'var(--text-muted, #999)' }}>
            <p>No text content found to map. Try uploading a document first.</p>
          </div>
        )}

        {!isGenerating && !error && nodes.length > 0 && (
          <ReactFlow 
            nodes={nodes} 
            edges={edges} 
            onNodeClick={(_, node) => onNodeClick && onNodeClick(node)}
            fitView
            fitViewOptions={{ padding: 0.2 }}
          >
            <Background color="var(--border-color, #ccc)" gap={16} />
            <Controls />
            <MiniMap />
          </ReactFlow>
        )}
      </div>
    </div>
  );
}